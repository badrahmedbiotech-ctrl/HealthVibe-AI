DEFAULT_LANG = "en"


def get_text(lang: str, key: str) -> str:
    """
    Safely fetch a translated string.
    Falls back to English if the language or key is missing,
    and returns a visible placeholder if the key doesn't exist anywhere
    (so a missing translation never crashes the app).
    """
    lang_dict = TEXTS.get(lang, TEXTS[DEFAULT_LANG])
    if key in lang_dict:
        return lang_dict[key]
    fallback = TEXTS[DEFAULT_LANG].get(key)
    return fallback if fallback is not None else f"[{key}]"


def get_lang_meta(lang: str) -> dict:
    """Return direction/font/switch-label info for a given language code."""
    return LANG_META.get(lang, LANG_META[DEFAULT_LANG])


def check_translation_keys_match():
    """
    Dev-time sanity check: ensures every language has the exact same set
    of keys.
    """
    all_keys = {lang: set(texts.keys()) for lang, texts in TEXTS.items()}
    reference_lang = DEFAULT_LANG
    reference_keys = all_keys[reference_lang]

    mismatches = {}
    for lang, keys in all_keys.items():
        if lang == reference_lang:
            continue
        missing = reference_keys - keys
        extra = keys - reference_keys
        if missing or extra:
            mismatches[lang] = {"missing": missing, "extra": extra}

    assert not mismatches, f"Translation key mismatch detected: {mismatches}"


